   static String apprentice(RandomSource random, boolean female) {
      return surname(random) + pick(random, female ? FEMALE_GIVEN_NAMES : MALE_GIVEN_NAMES);
   }

   static String master(RandomSource random) {
      return surname(random) + pick(random, MASTER_GIVEN_NAMES);
   }

   static boolean isGenericEntityName(Component name, String translationKey) {
      return name != null
         && name.getContents() instanceof TranslatableContents translatable
         && translationKey.equals(translatable.getKey());
   }

   private static String surname(RandomSource random) {
      return random.nextInt(100) < 6 ? pick(random, COMPOUND_SURNAMES) : pick(random, SURNAMES);
   }

   private static String pick(RandomSource random, String[] values) {
      return values[random.nextInt(values.length)];
   }
